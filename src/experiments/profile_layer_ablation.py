def run(
    profile_path: str,
    persona_path: str,
    output_dir: str,
    case_ids: tuple[str, ...] | None = None,
    overwrite: bool = False,
) -> dict[str, Any]:
    llm = LLMClient()
    raw = load_json(profile_path)
    full_profile = raw.get("state_axis", {}).get("static_profile", raw)
    persona = load_json(persona_path)
    cases = build_cases(full_profile)
    known_case_ids = {case["case_id"] for case in cases}
    if case_ids:
        selected_ids = set(case_ids)
        cases = tuple(case for case in cases if case["case_id"] in selected_ids)
    else:
        selected_ids = known_case_ids
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    results_path = output / "profile_layer_ablation_results.json"
    existing = load_json(str(results_path)).get("records", []) if results_path.exists() else []
    results: list[dict[str, Any]] = [r for r in existing if r.get("case_id") in known_case_ids]
    if overwrite:
        results = [r for r in results if r.get("case_id") not in selected_ids]
    completed = {r.get("case_id") for r in results}

    for case in cases:
        if case["case_id"] in completed:
            continue
        layer = case["layer"]
        field = case["field"]
        message = case["message"]
        target_profile = case["target_profile"]

        # Only this layer is ablated for this case; all other layers remain
        # available exactly as they are in the full-profile baseline.
        ablated_profile = deepcopy(full_profile)
        ablated_profile.pop(layer, None)

        baseline_response = _response(llm, message, full_profile, persona)
        baseline_activation = _activation(llm, message, baseline_response, full_profile)
        baseline_scores = _judge(llm, message, baseline_response, layer, field, target_profile)

        ablated_response = _response(llm, message, ablated_profile, persona)
        # First judge against what the ablated agent actually received.
        ablated_activation = _activation(llm, message, ablated_response, ablated_profile)
        # Then judge the same reply against the full profile.  If the removed
        # target field appears here, the remaining layers leaked target-layer
        # information and the test case is not isolated.
        full_reference_activation = _activation(llm, message, ablated_response, full_profile)
        ablated_scores = _judge(llm, message, ablated_response, layer, field, target_profile)

        target_leaked = _target_is_activated(full_reference_activation, layer, field)
        results.append({
            "case_id": case["case_id"],
            "target_layer": layer,
            "target_field": field,
            "target_profile": target_profile,
            "message": message,
            "design_rationale": case["design_rationale"],
            "baseline": {
                "agent_profile_scope": "full_profile",
                "response": baseline_response,
                "activation": baseline_activation,
                "target_activated": _target_is_activated(baseline_activation, layer, field),
                "scores": baseline_scores,
            },
            "ablated": {
                "agent_profile_scope": f"full_profile_without_{layer}",
                "response": ablated_response,
                "activation_with_ablated_candidates": ablated_activation,
                "activation_with_full_reference": full_reference_activation,
                "target_activated_with_ablated_candidates": _target_is_activated(ablated_activation, layer, field),
                "target_leaked_with_full_reference": target_leaked,
                "scores": ablated_scores,
            },
            "case_usable": not target_leaked,
        })
        # Persist every completed case; batches can safely resume after a
        # network interruption or command timeout.
        save_json(str(results_path), {"records": results})
        print(f"{case['case_id']} complete | leaked={target_leaked}")

    per_case: dict[str, Any] = {}
    for result in results:
        baseline_scores = result["baseline"]["scores"]
        ablated_scores = result["ablated"]["scores"]
        per_case[result["case_id"]] = {
            "target_layer": result["target_layer"],
            "target_field": result["target_field"],
            "case_usable": result["case_usable"],
            "baseline_target_activated": result["baseline"]["target_activated"],
            "ablated_target_activated": result["ablated"]["target_activated_with_ablated_candidates"],
            "target_leaked_with_full_reference": result["ablated"]["target_leaked_with_full_reference"],
            "baseline_scores": baseline_scores,
            "ablated_scores": ablated_scores,
            "ablation_delta": {
                metric: round(ablated_scores[metric] - baseline_scores[metric], 3)
                for metric in METRICS
            },
        }

    per_layer: dict[str, Any] = {}
    for layer in LAYERS:
        layer_results = [r for r in results if r["target_layer"] == layer]
        valid_layer_results = [r for r in layer_results if r["case_usable"]]
        per_layer[layer] = {
            "num_cases": len(layer_results),
            "usable_cases": len(valid_layer_results),
            "leaked_cases": len(layer_results) - len(valid_layer_results),
            "baseline_target_activation_rate": (
                sum(r["baseline"]["target_activated"] for r in layer_results) / len(layer_results)
                if layer_results else 0.0
            ),
            "mean_delta": {
                metric: _mean([
                    r["ablated"]["scores"][metric] - r["baseline"]["scores"][metric]
                    for r in valid_layer_results
                ])
                for metric in METRICS
            },
        }

    valid_results = [result for result in results if result["case_usable"]]
    summary = {
        "experiment_version": "single_layer_ablation_v2",
        "num_cases": len(results),
        "usable_cases": len(valid_results),
        "leaked_cases": [result["case_id"] for result in results if not result["case_usable"]],
        "per_case": per_case,
        "per_layer": per_layer,
        "valid_case_means": {
            "baseline": {
                metric: _mean([r["baseline"]["scores"][metric] for r in valid_results])
                for metric in METRICS
            },
            "ablated": {
                metric: _mean([r["ablated"]["scores"][metric] for r in valid_results])
                for metric in METRICS
            },
        },
        "run_at": datetime.now().isoformat(),
    }

    save_json(str(output / "profile_layer_ablation_results.json"), {"records": results})
    save_json(str(output / "profile_layer_ablation_summary.json"), summary)
    _write_report(output, summary)
    return summary


def _v3_post_json(url: str, payload: dict[str, Any], timeout: int = 60) -> dict[str, Any]:
    body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    request = urllib.request.Request(
        url,
        data=body,
        headers={"Content-Type": "application/json; charset=utf-8"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"HTTP {exc.code} from {url}: {detail}") from exc


def _v3_reset_service(workspace: Path, script_path: Path, port: int) -> None:
    completed = subprocess.run(
        [
            "powershell.exe",
            "-NoProfile",
            "-ExecutionPolicy",
            "Bypass",
            "-File",
            str(script_path),
            "-Workspace",
            str(workspace),
            "-Port",
            str(port),
        ],
        cwd=str(workspace),
        check=False,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if completed.returncode != 0:
        detail = (completed.stderr or completed.stdout).strip()
        raise RuntimeError(f"Failed to reset experiment service: {detail}")


def _v3_select_character(service_url: str, profile_id: str, persona_id: str) -> None:
    _v3_post_json(
        f"{service_url.rstrip('/')}/api/characters/select",
        {"profile_id": profile_id, "persona_id": persona_id},
        timeout=60,
    )


def _v3_chat_via_service(
    service_url: str,
    message: str,
    ablate_dimension: str | None,
    timeout: int,
) -> str:
    payload: dict[str, Any] = {"message": message}
    if ablate_dimension:
        payload["ablate_dimension"] = ablate_dimension
    body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    request = urllib.request.Request(
        f"{service_url.rstrip('/')}/api/chat",
        data=body,
        headers={"Content-Type": "application/json; charset=utf-8"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            for raw_line in response:
                if not raw_line.strip():
                    continue
                event = json.loads(raw_line.decode("utf-8"))
                if event.get("type") == "error":
                    raise RuntimeError(event.get("error", "unknown chat service error"))
                if event.get("type") == "done":
                    return event.get("message") or event.get("response") or ""
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"HTTP {exc.code} from /api/chat: {detail}") from exc
    raise RuntimeError("Chat service stream ended without a done event.")


def _v3_agent_response(
    workspace: Path,
    service_url: str,
    reset_script: Path,
    port: int,
    profile_id: str,
    persona_id: str,
    message: str,
    ablate_dimension: str | None,
    skip_service_reset: bool,
    chat_timeout: int,
) -> str:
    if not skip_service_reset:
        _v3_reset_service(workspace, reset_script, port)
    _v3_select_character(service_url, profile_id, persona_id)
    return _v3_chat_via_service(service_url, message, ablate_dimension, chat_timeout)


def _v3_coerce_score(value: Any) -> float:
    try:
        score = float(value)
    except (TypeError, ValueError):
        return 0.0
    return round(min(5.0, max(1.0, score)), 3)


def _v3_judge(
    llm: LLMClient,
    message: str,
    response: str,
    target_profile: dict[str, Any],
) -> dict[str, Any]:
    prompt = f"""你是用户画像消融实验的严格评审员。请只代入下面这个“目标层用户画像”中的用户，根据“用户输入”和“智能体回复”，给出一个主观满意度分数。

评价目标：判断这条回复是否让该目标层画像真正发挥了作用。不要补充、猜测或使用其他层级的用户画像信息；不要拆分维度，只给一个总分。

目标层用户画像：
{json.dumps(target_profile, ensure_ascii=False, indent=2)}

用户输入：
{message}

智能体回复：
{response}

请严格按照 1-5 分标准评分：

1 分：回复答非所问、明显误解用户，或与用户画像中的核心需求/偏好相冲突；用户大概率觉得没有帮助。
2 分：回复表面相关，但很泛泛，几乎没有体现该用户画像；建议弱、套话多，用户只能获得很有限帮助。
3 分：回复基本可用，能回应当前问题，但个性化程度有限；像一般用户也能收到的合理建议。
4 分：回复明显贴合该用户画像，能结合其偏好、处境或表达方式给出具体帮助；用户大概率会觉得被理解。
5 分：回复高度贴合该用户，既抓住当前输入，也自然利用画像中的关键线索，建议清晰、具体、有长期价值；用户会觉得非常有帮助。

只输出 JSON，不要输出解释性正文：
{{"score": number, "reason": "一句话说明评分依据"}}"""
    try:
        result = parse_json(llm.chat(
            "You are a strict evaluator. Output only JSON.",
            prompt,
            temperature=0.0,
            max_tokens=220,
        ))
    except Exception as exc:
        return {"score": 0.0, "reason": f"evaluation_failed: {exc}"}
    return {
        "score": _v3_coerce_score(result.get("score")),
        "reason": str(result.get("reason", "")).strip(),
    }


